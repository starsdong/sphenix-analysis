// ptres_study.C : is the high-pT drop of the silicon efficiency a momentum-resolution (migration) effect?
//   root -l -b -q 'scripts/ptres_study.C("<note root>")'
// Input : <note>/../ntuples/TrackQA_run79509_seg000-099.root (v2: has tpcSeedPt for every track)
// Idea  : numerator tracks (TPC+silicon) have a better pT resolution than the TPC-only tracks in the
//         denominator; a steeply falling spectrum smeared more strongly migrates more tracks to high pT, so
//         eff(pT) = N_Si(pT_full) / [N_Si(pT_full) + N_TPConly(pT_TPConly)] drops at high pT.
//         Test: use the SAME TPC-only estimator (TPC seed pT) for numerator and denominator.
// Output: figures/fig_ptres_*.{pdf,png}, tables/ptres_numbers.tex, tables/ptres_defaults.tex,
//         tables/tab_ptres.tex, logs/ptres_numbers.txt
#include <TFile.h>
#include <TTree.h>
#include <TH1D.h>
#include <TH2D.h>
#include <TF1.h>
#include <TCanvas.h>
