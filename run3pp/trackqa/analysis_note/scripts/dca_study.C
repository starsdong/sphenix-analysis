// dca_study.C : DCA_xy / DCA_z study on the 100-segment TrackQA sample (run 79509 seg 0-99).
//   root -l -b -q 'scripts/dca_study.C("<note root>")'
// Input : <note>/../ntuples/TrackQA_run79509_seg000-099.root (hadd of 100 per-segment ntuples)
//         <note>/logs/stat100_jobs.txt (per-job summary written on the cluster)
// Output: figures/fig_dca_*.{pdf,png}, tables/tab_dca_*.tex, tables/dca_numbers.tex, tables/dca_defaults.tex,
//         logs/dca_numbers.txt
// Selection (all plots): silicon "good" tracks MVTX>=3, INTT>=1, TPC>=20 clusters, p = pT cosh(eta) > 0.8 GeV/c,
//   sample A: vtxMatch==1 (track used in the vertex fit), sample B: vtxMatch==2 (vertex id, not in the fit).
// Widths: Gaussian core, iterative fit in mean +- 2 sigma (4 iterations), on 10-um bins.
