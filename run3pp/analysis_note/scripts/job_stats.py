#!/usr/bin/env python3
"""Job statistics for the note: parses logs/condor_471173.txt and logs/kfp_job_summary.txt.
Writes logs/job_stats.txt and tables/jobstats.tex (LaTeX macros)."""
import re
import statistics as st
import sys
from pathlib import Path

root = Path(sys.argv[1]).resolve()
assert (root / "main.tex").exists(), f"not a note root: {root}"
logs, tabs = root / "logs", root / "tables"

wall, cpu, ok = [], [], 0
for line in (logs / "condor_471173.txt").read_text().splitlines():
    f = line.split()
    if len(f) < 4:
        continue
    ok += f[1] == "0"
    wall.append(float(f[2]))
    cpu.append(float(f[3]))

per = {}
ncand = {}
nlogs = ndone = 0
rss = []
for block in (logs / "kfp_job_summary.txt").read_text().split("== ")[1:]:
    nlogs += 1
    ndone += "All done" in block
    for m in re.finditer(r"(\w+)_TOP: per event time \(ms\):\s+([\d.]+)", block):
        per.setdefault(m.group(1), []).append(float(m.group(2)))
    for m in re.finditer(r"object (\w+) finished\. Number of candidates: (\d+)", block):
        ncand.setdefault(m.group(1), []).append(int(m.group(2)))
    m = re.search(r"Maximum resident set size \(kbytes\): (\d+)", block)
    if m:
        rss.append(int(m.group(1)) / 1024**2)

mac = {
    "nCondorJobs": str(len(wall)),
    "nCondorOK": str(ok),
    "nKFPlogs": str(nlogs),
    "nKFPdone": str(ndone),
    "condorWallMin": f"{st.mean(wall)/60:.0f}",
    "condorWallMaxMin": f"{max(wall)/60:.0f}",
    "maxRSSGB": f"{max(rss):.2f}",
}
names = {"Ks_reco": "Ks", "Lambda_reco": "Lambda", "D0_reco": "Dzero", "Ks_noXmatch": "KsNoX", "Lambda_noXmatch": "LambdaNoX", "EventInfoTree": "EvInfo"}
for k, v in per.items():
    if k in names:
        mac["msPerEv" + names[k]] = f"{st.mean(v):.0f}"
prod = sum(st.mean(per[k]) for k in ("Ks_reco", "Lambda_reco", "D0_reco"))
mac["msPerEvProd"] = f"{prod:.0f}"
mac["minPerFileProd"] = f"{prod*990/1000/60:.1f}"
total = sum(sum(v) for k, v in ncand.items() if k in ("Ks_reco",))
mac["nCandKsFromLogs"] = f"{total:,}"

# cross-check: Ks candidates counted by KFParticle in the job logs == entries of the merged ntuple
nums = dict(l.split(" = ", 1) for l in (logs / "numbers.txt").read_text().splitlines() if " = " in l and not l.startswith("#"))
mac["checkCandLogs"] = "PASS" if mac["nCandKsFromLogs"] == nums["nCandKs"] else "FAIL"
mac["checkLogsDone"] = "PASS" if ndone == nlogs == 31 and ok == len(wall) == 30 else "FAIL"
# dataset size (inventory at the time of the test) and full-production extrapolation
nfiles = sum(int(l.split()[1]) for l in (logs / "dataset_inventory.txt").read_text().splitlines() if l.strip())
evPerFile = float(nums["nEvents"].replace(",", "")) / 31
kb = sum(float(nums[k]) for k in ("kBPerEvKs", "kBPerEvLambda", "kBPerEvDzero"))
mac["nDSTfiles"] = f"{nfiles:,}"
mac["evPerFile"] = f"{evPerFile:.0f}"
mac["nEvFullE"] = f"{nfiles*evPerFile/1e8:.1f}"
mac["kBPerEvProd"] = f"{kb:.1f}"
mac["TBFull"] = f"{nfiles*evPerFile*kb*1024/1e12:.1f}"
mac["kCPUhFull"] = f"{nfiles*evPerFile*prod/1e3/3600/1e3:.0f}"

(logs / "job_stats.txt").write_text("".join(f"{k} = {v}\n" for k, v in mac.items()))
(tabs / "jobstats.tex").write_text("% generated by scripts/job_stats.py\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in mac.items()))
print((logs / "job_stats.txt").read_text())
