#!/usr/bin/env python3
"""make_numbers.py <note root>: turn logs/*_values.txt ("KEY value") and logs/provenance_cluster.txt into
tables/numbers.tex (\\newcommand per number). Macro names are letters only; duplicates abort."""
import re, sys
from pathlib import Path

root = Path(sys.argv[1]).resolve()
assert (root / "main.tex").exists() and (root / "logs").is_dir(), f"not a note root: {root}"
macros = {}


def add(k, v):
    assert re.fullmatch(r"[A-Za-z]+", k), f"bad macro name {k}"
    assert k not in macros, f"duplicate macro {k}"
    macros[k] = v


def big(x):
    return f"{int(x):,}".replace(",", "{,}")


for f in sorted((root / "logs").glob("*_values.txt")):
    for line in f.read_text().splitlines():
        if line.strip():
            k, v = line.split(None, 1)
            add(k, v.strip())

# provenance from the cluster (skim job outputs)
prov = (root / "logs" / "provenance_cluster.txt").read_text()
ten = [tuple(map(int, m)) for m in re.findall(r"skim_d0: (\d+) files, (\d+) -> (\d+) candidates", prov)]
add("tenFiles", big(sum(t[0] for t in ten)))
add("tenIn", big(sum(t[1] for t in ten)))
add("tenOut", big(sum(t[2] for t in ten)))
add("tenFrac", f"{100 * sum(t[2] for t in ten) / sum(t[1] for t in ten):.2f}")
m = re.search(r"fullskim files (\d+) in (\d+) out (\d+)", prov)
fF, fI, fO = map(int, m.groups())
add("fullFiles", big(fF))
add("fullIn", big(fI))
add("fullOut", big(fO))
add("fullFrac", f"{100 * fO / fI:.2f}")
add("fullJobsOK", re.search(r"fullskim_jobs_ok (\d+)", prov).group(1))
add("fullJobsFailed", re.search(r"fullskim_jobs_failed (\d+)", prov).group(1))
tight = [tuple(map(int, m)) for m in re.findall(r"skim_d0_tight: (\d+) files, (\d+) -> (\d+) candidates", prov)]
add("tightIn", big(sum(t[1] for t in tight)))
add("tightOut", big(sum(t[2] for t in tight)))
add("tightFrac", f"{100 * sum(t[2] for t in tight) / sum(t[1] for t in tight):.1f}")
m = re.search(r"prod90pct_status .*ok=(\d+) bad=(\d+) seg=(\d+) evt=(\d+) size=([\d.]+)", prov)
add("ninetyJobs", big(m.group(1)))
add("ninetyBad", m.group(2))
add("ninetySeg", big(m.group(3)))
add("ninetyEvt", big(m.group(4)))
add("ninetySize", m.group(5))
add("tenDZfiles", big(re.search(r"prod10pct_D0_files (\d+)", prov).group(1)))
# hand scan: largest z among fits with an acceptable background description (chi2/ndf < 2)
rows = re.findall(r"^(S\d+)\s.*?fixed: S=\s*(-?[\d.]+) \+-\s*([\d.]+) \(z=\s*(-?[\d.]+)\) chi2/ndf=([\d.]+)",
                  (root / "logs" / "scan.txt").read_text(), re.M)
assert len(rows) == int(macros["scanN"]), "scan.txt parse"
good = [r for r in rows if float(r[4]) < 2]
best = max(good, key=lambda r: float(r[3]))
add("scanGoodN", str(len(good)))
add("scanZmaxGood", f"{float(best[3]):.1f}")
add("scanZmaxGoodSel", best[0])
add("scanChiMax", f"{max(float(r[4]) for r in rows):.1f}")
add("scanBadSels", ", ".join(r[0] for r in rows if float(r[4]) >= 2))
add("scanZminAll", f"{min(float(r[3]) for r in rows):.1f}")
# consistency checks (PASS/FAIL macros cited in the audit)
add("chkTenFiles", "PASS" if sum(t[0] for t in ten) == int(re.search(r"prod10pct_D0_files (\d+)", prov).group(1)) else "FAIL")
add("chkFullSum", "PASS" if sum(t[1] for t in tight) == fO else "FAIL")
add("chkTenEntries", "PASS" if macros.get("nTen", "").replace("{,}", "") == str(sum(t[2] for t in ten)) else "FAIL")
add("chkFullEntries", "PASS" if macros.get("nFull", "").replace("{,}", "") == str(sum(t[2] for t in tight)) else "FAIL")

out = root / "tables" / "numbers.tex"
out.write_text("% generated by scripts/make_numbers.py -- do not edit\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items()))
print(f"{len(macros)} macros -> {out}")
for k in [k for k in macros if k.startswith("chk")]:
    print(k, macros[k])
